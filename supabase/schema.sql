create extension if not exists pgcrypto;

create table if not exists public.locations (
  id bigint generated by default as identity primary key,
  name text not null unique,
  city text not null default 'Quito',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  name text not null unique,
  color text not null default '#dbeafe',
  counts_hours boolean not null default true,
  active boolean not null default true
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  full_name text not null default '',
  app_role text not null default 'supervisor'
    check (app_role in ('admin','supervisor')),
  location_id bigint references public.locations(id),
  active boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.profile_locations (
  profile_id uuid not null references public.profiles(id) on delete cascade,
  location_id bigint not null references public.locations(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(profile_id,location_id)
);

insert into public.profile_locations(profile_id,location_id)
select id,location_id from public.profiles where location_id is not null
on conflict do nothing;

create table if not exists public.supervisors (
  id bigint generated by default as identity primary key,
  name text not null,
  location_id bigint not null references public.locations(id),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  supervisor_id bigint not null references public.supervisors(id) on delete cascade,
  work_date date not null,
  start_time time,
  end_time time,
  role_id bigint not null references public.roles(id),
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(supervisor_id, work_date)
);

create table if not exists public.shopper_staff(
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check(category in ('purchase','delivery')),
  employment_type text not null default 'Interno',
  location_id bigint not null references public.locations(id),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.shopper_staff add column if not exists shopper_external_id text;
drop index if exists public.shopper_staff_external_id_unique;

create table if not exists public.shopper_shift_types(
  id bigint generated by default as identity primary key,
  code text not null,
  label text not null,
  start_time time,
  end_time time,
  category text not null default 'both' check(category in ('purchase','delivery','both')),
  location_id bigint references public.locations(id) on delete cascade,
  counts_opening boolean not null default false,
  counts_closing boolean not null default false,
  is_free boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists shopper_shift_types_scope_unique
on public.shopper_shift_types(coalesce(location_id,0),category,code);

create table if not exists public.shopper_turns(
  id bigint generated by default as identity primary key,
  staff_id bigint not null references public.shopper_staff(id) on delete cascade,
  work_date date not null,
  turn_code text not null check(turn_code in ('A','A2','B','T','I','N','L','V')),
  updated_at timestamptz not null default now(),
  unique(staff_id,work_date)
);
alter table public.shopper_turns drop constraint if exists shopper_turns_turn_code_check;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id,email,full_name)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'full_name',''))
  on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from profiles where id=auth.uid() and app_role='admin' and active);
$$;

create or replace function public.my_location()
returns bigint language sql stable security definer set search_path = public as $$
  select location_id from profiles where id=auth.uid() and active;
$$;

create or replace function public.has_location(target_location bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists(
    select 1 from profile_locations pl
    join profiles p on p.id=pl.profile_id
    where pl.profile_id=auth.uid() and pl.location_id=target_location and p.active
  );
$$;

