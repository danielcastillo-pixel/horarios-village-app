create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id,email,full_name)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'full_name',''))
  on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from profiles where id=auth.uid() and app_role='admin' and active);
$$;

create or replace function public.my_location()
returns bigint language sql stable security definer set search_path = public as $$
  select location_id from profiles where id=auth.uid() and active;
$$;

create or replace function public.has_location(target_location bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists(
    select 1 from profile_locations pl
    join profiles p on p.id=pl.profile_id
    where pl.profile_id=auth.uid() and pl.location_id=target_location and p.active
  );
$$;

