drop policy if exists locations_read on public.locations;
create policy locations_read on public.locations for select to authenticated
using (public.is_admin() or public.has_location(id));
drop policy if exists locations_admin on public.locations;
create policy locations_admin on public.locations for all to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists roles_read on public.roles;
create policy roles_read on public.roles for select to authenticated using (active or public.is_admin());
drop policy if exists roles_admin on public.roles;
create policy roles_admin on public.roles for all to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists profiles_read on public.profiles;
create policy profiles_read on public.profiles for select to authenticated
using (id=auth.uid() or public.is_admin());
drop policy if exists profiles_admin on public.profiles;
create policy profiles_admin on public.profiles for all to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists profile_locations_read on public.profile_locations;
create policy profile_locations_read on public.profile_locations for select to authenticated
using (profile_id=auth.uid() or public.is_admin());
drop policy if exists profile_locations_admin on public.profile_locations;
create policy profile_locations_admin on public.profile_locations for all to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists supervisors_read on public.supervisors;
create policy supervisors_read on public.supervisors for select to authenticated
using (public.is_admin() or public.has_location(location_id));
drop policy if exists supervisors_admin on public.supervisors;
create policy supervisors_admin on public.supervisors for all to authenticated
using (public.is_admin()) with check (public.is_admin());
drop policy if exists supervisors_assigned_write on public.supervisors;
create policy supervisors_assigned_write on public.supervisors for all to authenticated
using (public.has_location(location_id))
with check (public.has_location(location_id));

drop policy if exists assignments_read on public.assignments;
create policy assignments_read on public.assignments for select to authenticated
using (exists(select 1 from supervisors s where s.id=supervisor_id
  and (public.is_admin() or public.has_location(s.location_id))));
drop policy if exists assignments_write on public.assignments;
create policy assignments_write on public.assignments for all to authenticated
using (exists(select 1 from supervisors s where s.id=supervisor_id
  and (public.is_admin() or public.has_location(s.location_id))))
with check (exists(select 1 from supervisors s where s.id=supervisor_id
  and (public.is_admin() or public.has_location(s.location_id))));

drop policy if exists shopper_staff_access on public.shopper_staff;
create policy shopper_staff_access on public.shopper_staff for all to authenticated
using(public.is_admin() or public.has_location(location_id))
with check(public.is_admin() or public.has_location(location_id));

drop policy if exists shopper_shift_types_access on public.shopper_shift_types;
create policy shopper_shift_types_access on public.shopper_shift_types for all to authenticated
using(public.is_admin() or location_id is null or public.has_location(location_id))
with check(public.is_admin() or (location_id is not null and public.has_location(location_id)));

drop policy if exists shopper_turns_access on public.shopper_turns;
create policy shopper_turns_access on public.shopper_turns for all to authenticated
using(exists(select 1 from public.shopper_staff s where s.id=staff_id
  and (public.is_admin() or public.has_location(s.location_id))))
with check(exists(select 1 from public.shopper_staff s where s.id=staff_id
  and (public.is_admin() or public.has_location(s.location_id))));

