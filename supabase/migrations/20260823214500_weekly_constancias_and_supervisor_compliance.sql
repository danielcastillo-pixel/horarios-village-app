drop policy if exists weekly_evidence_insert on storage.objects;
create policy weekly_evidence_insert on storage.objects for insert to authenticated
with check (
  bucket_id='weekly-evidence'
  and (storage.foldername(name))[1]=(select auth.uid())::text
  and private.is_active_user()
);

drop policy if exists weekly_evidence_select on storage.objects;
create policy weekly_evidence_select on storage.objects for select to authenticated
using (
  bucket_id='weekly-evidence'
  and (
    owner_id=(select auth.uid())::text
    or public.is_admin()
    or exists (
      select 1 from public.weekly_evidences evidence
      where evidence.evidence_path=name and public.has_location(evidence.location_id)
    )
  )
);
