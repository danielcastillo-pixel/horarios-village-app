with check (
  bucket_id='regional-evidence'
  and (storage.foldername(name))[1]=(select auth.uid())::text
  and (select private.is_active_user())
);

drop policy if exists regional_evidence_select on storage.objects;
create policy regional_evidence_select on storage.objects for select to authenticated
using (
  bucket_id='regional-evidence'
  and (
    owner_id=(select auth.uid())::text
    or (select public.is_admin())
    or exists(select 1 from public.regional_clients client where name=any(client.evidence_paths))
  )
);
