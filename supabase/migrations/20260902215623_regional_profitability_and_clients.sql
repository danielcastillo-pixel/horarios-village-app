create or replace function private.protect_regional_client()
returns trigger
language plpgsql
security definer
set search_path=pg_catalog,public,private
as $$
declare
  actor uuid:=(select auth.uid());
  actor_name text;
  actor_admin boolean;
begin
  select coalesce(nullif(trim(full_name),''),email),app_role='admin' and active
  into actor_name,actor_admin
  from public.profiles where id=actor and active;
  if actor_name is null then raise exception 'Usuario no autorizado.' using errcode='42501';end if;
  if tg_op='INSERT' then
    new.submitted_by:=actor;
    new.submitted_by_name:=actor_name;
    if new.client_type='blacklist' and not actor_admin then
      new.blacklist_status:='pending';new.approved_by:=null;new.approved_at:=null;
    elsif new.client_type='blacklist' and actor_admin and new.blacklist_status<>'pending' then
      new.approved_by:=actor;new.approved_at:=now();
    end if;
  else
    new.client_type:=old.client_type;
    new.client_external_id:=old.client_external_id;
    new.submitted_by:=old.submitted_by;
    new.submitted_by_name:=old.submitted_by_name;
    new.created_at:=old.created_at;
    if not actor_admin then
      new.blacklist_status:=old.blacklist_status;
      new.approved_by:=old.approved_by;
      new.approved_at:=old.approved_at;
    elsif new.client_type='blacklist' and new.blacklist_status is distinct from old.blacklist_status then
      new.approved_by:=actor;new.approved_at:=now();
    end if;
  end if;
  new.updated_at:=now();
  return new;
end;
$$;
revoke all on function private.protect_regional_client() from public,anon,authenticated;
drop trigger if exists protect_regional_client on public.regional_clients;
create trigger protect_regional_client before insert or update on public.regional_clients
for each row execute function private.protect_regional_client();

