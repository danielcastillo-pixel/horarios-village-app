-- Gestión semanal de rentabilidad y clientes de Región Sur.

create table if not exists public.regional_weekly_kpis (
  id bigint generated by default as identity primary key,
  week_start date not null,
  city text not null check (length(trim(city)) between 2 and 120),
  sales numeric(14,2) not null default 0 check (sales >= 0),
  orders integer not null default 0 check (orders >= 0),
  active_clients integer not null default 0 check (active_clients >= 0),
  average_ticket numeric(12,2) not null default 0 check (average_ticket >= 0),
  margin_percent numeric(7,2) not null default 0 check (margin_percent between -100 and 1000),
  late_percent numeric(7,2) not null default 0 check (late_percent between 0 and 100),
  rescheduling_percent numeric(7,2) not null default 0 check (rescheduling_percent between 0 and 100),
  oos_percent numeric(7,2) not null default 0 check (oos_percent between 0 and 100),
  incidents integer not null default 0 check (incidents >= 0),
  analysis text not null default '' check (length(analysis) <= 5000),
  affected_clients text not null default '' check (length(affected_clients) <= 5000),
  affected_sectors text not null default '' check (length(affected_sectors) <= 3000),
  action_plan text not null default '' check (length(action_plan) <= 5000),
  meeting_summary text not null default '' check (length(meeting_summary) <= 5000),
  created_by uuid not null references public.profiles(id),
  updated_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (week_start, city),
  constraint regional_weekly_kpis_monday_check check (extract(isodow from week_start)=1)
);

create table if not exists public.regional_meetings (
  id bigint generated by default as identity primary key,
  week_start date not null,
  meeting_date date not null,
  meeting_time time,
  meeting_type text not null check (meeting_type in ('individual','group','city')),
  title text not null check (length(trim(title)) between 3 and 180),
  participants text not null check (length(trim(participants)) between 2 and 2000),
  cities text not null default '' check (length(cities) <= 1000),
  topics text not null check (length(trim(topics)) between 3 and 5000),
  agreements text not null default '' check (length(agreements) <= 5000),
  responsible text not null default '' check (length(responsible) <= 1000),
  due_date date,
  status text not null default 'open' check (status in ('open','done')),
  evidence_paths text[] not null default '{}'::text[],
  created_by uuid not null references public.profiles(id),
  updated_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint regional_meetings_monday_check check (extract(isodow from week_start)=1),
  constraint regional_meetings_date_check check (meeting_date between week_start and week_start+6),
  constraint regional_meetings_evidence_check check (cardinality(evidence_paths) <= 10 and array_position(evidence_paths,null) is null)
);

create table if not exists public.regional_requests (
  id bigint generated by default as identity primary key,
  week_start date not null,
  city text not null check (length(trim(city)) between 2 and 120),
  target_area text not null check (target_area in ('marketing','b2b','commercial','operations','other')),
  request_text text not null check (length(trim(request_text)) between 3 and 5000),
  rationale text not null default '' check (length(rationale) <= 5000),
  priority text not null default 'medium' check (priority in ('low','medium','high')),
  responsible text not null default '' check (length(responsible) <= 1000),
  due_date date,
  status text not null default 'pending' check (status in ('pending','requested','in_progress','completed','rejected')),
  created_by uuid not null references public.profiles(id),
  updated_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint regional_requests_monday_check check (extract(isodow from week_start)=1)
);

create table if not exists public.regional_clients (
  id bigint generated by default as identity primary key,
  client_type text not null check (client_type in ('potential','blacklist')),
  client_external_id text not null check (length(trim(client_external_id)) between 1 and 120),
  client_name text not null check (length(trim(client_name)) between 2 and 200),
  city text not null check (length(trim(city)) between 2 and 120),
  sector text not null default '' check (length(sector) <= 500),
  estimated_orders integer check (estimated_orders is null or estimated_orders >= 0),
  responsible text not null default '' check (length(responsible) <= 500),
  observations text not null default '' check (length(observations) <= 5000),
  next_action text not null default '' check (length(next_action) <= 3000),
  next_action_date date,
  potential_status text not null default 'pending' check (potential_status in ('pending','contacted','interested','converted','discarded')),
  blacklist_reason text not null default '' check (length(blacklist_reason) <= 5000),
  order_reference text not null default '' check (length(order_reference) <= 200),
  evidence_paths text[] not null default '{}'::text[],
  blacklist_status text not null default 'pending' check (blacklist_status in ('pending','restricted','enabled','rejected')),
  submitted_by uuid not null references public.profiles(id),
  submitted_by_name text not null,
  approved_by uuid references public.profiles(id),
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint regional_clients_evidence_check check (cardinality(evidence_paths) <= 10 and array_position(evidence_paths,null) is null),
  constraint regional_clients_blacklist_reason_check check (client_type='potential' or length(trim(blacklist_reason)) >= 3)
);

