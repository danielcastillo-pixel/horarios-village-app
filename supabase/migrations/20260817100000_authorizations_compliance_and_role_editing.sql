create or replace function private.audit_role_change()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $$
declare
  actor uuid := (select auth.uid());
  actor_name text;
begin
  select coalesce(nullif(trim(full_name),''),email)
  into actor_name from public.profiles where id=actor and active;
  if actor_name is null then
    raise exception 'Usuario no autorizado.' using errcode='42501';
  end if;
  new.updated_by:=actor;
  new.updated_by_name:=actor_name;
  new.updated_at:=now();
  if old.active and not new.active then new.archived_at:=now(); end if;
  if not old.active and new.active then new.archived_at:=null; end if;
  return new;
end;
$$;
revoke all on function private.audit_role_change() from public, anon, authenticated;
drop trigger if exists audit_role_change on public.roles;
create trigger audit_role_change before update on public.roles
for each row execute function private.audit_role_change();

create table if not exists public.authorization_requests (
  id bigint generated by default as identity primary key,
  request_type text not null check (request_type in ('discount','incentive')),
  location_id bigint not null references public.locations(id) on delete restrict,
  location_name_snapshot text not null,
  shopper_name text not null check (length(trim(shopper_name)) between 2 and 180),
  shopper_external_id text not null default '',
  order_number text not null check (length(trim(order_number)) between 2 and 80),
  client_name text not null check (length(trim(client_name)) between 2 and 180),
  amount numeric(12,2) not null check (amount > 0 and amount <= 999999.99),
  reason text not null check (length(trim(reason)) between 5 and 4000),
  evidence_path text not null check (length(trim(evidence_path)) between 5 and 500),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  decision_comment text not null default '',
  created_by uuid not null,
  created_by_name text not null,
  created_by_email text not null,
  created_at timestamptz not null default now(),
  decided_by uuid,
  decided_by_name text,
  decided_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint authorization_decision_check check (
    (status='pending' and decided_by is null and decided_at is null)
    or (status in ('approved','rejected') and decided_by is not null and decided_at is not null)
  )
);
create index if not exists authorization_requests_location_created_idx
  on public.authorization_requests (location_id, created_at desc);
create index if not exists authorization_requests_status_created_idx
  on public.authorization_requests (status, created_at desc);
create index if not exists authorization_requests_monthly_approved_idx
  on public.authorization_requests (location_id, request_type, created_at)
  where status='approved';

alter table public.authorization_requests enable row level security;
grant select,insert,update on table public.authorization_requests to authenticated;
grant usage,select on sequence public.authorization_requests_id_seq to authenticated;

drop policy if exists authorization_requests_read on public.authorization_requests;
create policy authorization_requests_read on public.authorization_requests for select to authenticated
using (public.is_admin() or public.has_location(location_id));
drop policy if exists authorization_requests_insert on public.authorization_requests;
create policy authorization_requests_insert on public.authorization_requests for insert to authenticated
with check (
  created_by=(select auth.uid())
  and status='pending'
  and (public.is_admin() or public.has_location(location_id))
);
drop policy if exists authorization_requests_admin_update on public.authorization_requests;
create policy authorization_requests_admin_update on public.authorization_requests for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create or replace function private.protect_authorization_request()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $$
declare
  actor uuid := (select auth.uid());
  actor_name text;
  actor_email text;
  local_name text;
  actor_is_admin boolean;
begin
  select coalesce(nullif(trim(full_name),''),email),email,app_role='admin'
  into actor_name,actor_email,actor_is_admin
  from public.profiles where id=actor and active;
  if actor_email is null then raise exception 'Usuario no autorizado.' using errcode='42501'; end if;

  if tg_op='INSERT' then
    select name into local_name from public.locations where id=new.location_id and active;
    if local_name is null then raise exception 'Local no disponible.' using errcode='23514'; end if;
    new.location_name_snapshot:=local_name;
    new.created_by:=actor;
    new.created_by_name:=actor_name;
    new.created_by_email:=actor_email;
    new.created_at:=now();
    new.status:='pending';
    new.decision_comment:='';
    new.decided_by:=null;
    new.decided_by_name:=null;
    new.decided_at:=null;
  else
    if not actor_is_admin then raise exception 'Solo el administrador puede decidir solicitudes.' using errcode='42501'; end if;
    new.request_type:=old.request_type;
    new.location_id:=old.location_id;
    new.location_name_snapshot:=old.location_name_snapshot;
    new.shopper_name:=old.shopper_name;
    new.shopper_external_id:=old.shopper_external_id;
    new.order_number:=old.order_number;
    new.client_name:=old.client_name;
    new.amount:=old.amount;
    new.reason:=old.reason;
    new.evidence_path:=old.evidence_path;
    new.created_by:=old.created_by;
    new.created_by_name:=old.created_by_name;
    new.created_by_email:=old.created_by_email;
    new.created_at:=old.created_at;
    if new.status='pending' then
      new.decided_by:=null; new.decided_by_name:=null; new.decided_at:=null;
    else
      new.decided_by:=actor; new.decided_by_name:=actor_name; new.decided_at:=now();
    end if;
  end if;
  new.updated_at:=now();
  return new;
end;
$$;
revoke all on function private.protect_authorization_request() from public, anon, authenticated;
drop trigger if exists protect_authorization_request on public.authorization_requests;
create trigger protect_authorization_request before insert or update on public.authorization_requests
for each row execute function private.protect_authorization_request();

