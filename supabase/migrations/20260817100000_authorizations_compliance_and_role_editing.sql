-- Evidencias privadas. El nombre inicia con el UUID del usuario que sube el archivo.
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('authorization-evidence','authorization-evidence',false,8388608,array['image/jpeg','image/png','image/webp','image/heic','image/heif'])
on conflict (id) do update set
  public=false,file_size_limit=excluded.file_size_limit,allowed_mime_types=excluded.allowed_mime_types;

drop policy if exists authorization_evidence_insert on storage.objects;
create policy authorization_evidence_insert on storage.objects for insert to authenticated
with check (
  bucket_id='authorization-evidence'
  and (storage.foldername(name))[1]=(select auth.uid())::text
  and private.is_active_user()
);
drop policy if exists authorization_evidence_select on storage.objects;
create policy authorization_evidence_select on storage.objects for select to authenticated
using (
  bucket_id='authorization-evidence'
  and (
    owner_id=(select auth.uid())::text
    or public.is_admin()
    or exists (
      select 1 from public.authorization_requests request
      where request.evidence_path=name and public.has_location(request.location_id)
    )
  )
);
