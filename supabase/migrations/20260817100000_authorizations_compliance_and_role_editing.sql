  id bigint generated by default as identity primary key,
  location_id bigint not null references public.locations(id) on delete restrict,
  location_name_snapshot text not null,
  week_start date not null,
  week_end date not null,
  activity_type text not null check (activity_type in ('shopper_purchase','shopper_delivery','supervisor_schedule')),
  submitted_by uuid not null,
  submitted_by_name text not null,
  submitted_by_email text not null,
  submitted_at timestamptz not null default now(),
  last_updated_by uuid not null,
  last_updated_by_name text not null,
  updated_at timestamptz not null default now(),
  unique (location_id, week_start, activity_type),
  constraint weekly_activity_monday_check check (extract(isodow from week_start)=1),
  constraint weekly_activity_end_check check (week_end=week_start+6)
);
create index if not exists weekly_activity_week_location_idx
  on public.weekly_activity_submissions (week_start desc, location_id);
create index if not exists weekly_activity_submitter_idx
  on public.weekly_activity_submissions (submitted_by, week_start desc);
alter table public.weekly_activity_submissions enable row level security;
grant select,insert,update on table public.weekly_activity_submissions to authenticated;
grant usage,select on sequence public.weekly_activity_submissions_id_seq to authenticated;

