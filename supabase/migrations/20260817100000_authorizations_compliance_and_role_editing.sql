using (public.is_admin() or public.has_location(location_id));
drop policy if exists weekly_activity_insert on public.weekly_activity_submissions;
create policy weekly_activity_insert on public.weekly_activity_submissions for insert to authenticated
with check (submitted_by=(select auth.uid()) and (public.is_admin() or public.has_location(location_id)));
drop policy if exists weekly_activity_update on public.weekly_activity_submissions;
